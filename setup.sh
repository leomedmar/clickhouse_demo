#!/usr/bin/env bash
# One-time setup on a new machine:
#   - creates the data/log folders mounted by docker-compose.yml
#   - creates .env with a random password for the ClickHouse "default" user (if missing)
#   - writes config/client/config.xml with that same password, so clickhouse-client
#     inside the containers works without typing it
# Safe to run more than once.
set -euo pipefail
cd "$(dirname "$0")"

for d in keeper-1 keeper-2 keeper-3 clickhouse-1 clickhouse-2 clickhouse-3 clickhouse-4; do
  mkdir -p "$d/data" "$d/logs"
done

if [ ! -f .env ]; then
  # finite input (head first) so no SIGPIPE under pipefail
  pw="lab_$(head -c 48 /dev/urandom | base64 | LC_ALL=C tr -dc 'A-Za-z0-9' | cut -c1-16)"
  printf '# Password for the ClickHouse "default" user (local lab only, do not commit)\nCH_PASSWORD=%s\n' "$pw" > .env
  chmod 600 .env
  echo "Created .env with a new random password."
else
  echo ".env already exists — keeping the current password."
fi

# shellcheck disable=SC1091
source .env
mkdir -p config/client
cat > config/client/config.xml <<XML
<!-- GENERATED by setup.sh from .env — do not edit by hand. -->
<!-- Credentials for clickhouse-client INSIDE the containers (docker exec ... clickhouse-client). -->
<config>
    <user>default</user>
    <password>${CH_PASSWORD}</password>
</config>
XML
echo "Wrote config/client/config.xml."
echo "Next: ./cluster.sh up -d   (picks the right compose files for Linux, macOS or Windows)"
